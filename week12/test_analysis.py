"""12주차 정제 함수 검증 테스트"""
from analysis import 원본, 미니원본, 정제, 반별평균


def test_정제하면_100행이_남는다():
    결과 = 정제(원본)
    assert len(결과) == 100


def test_정제후_반은_두종류다():
    결과 = 정제(원본)
    assert set(결과["반"].unique()) == {"1반", "2반"}


def test_그룹합의_합이_전체합과_같다():
    결과 = 정제(원본)
    반별합계의합 = 결과.groupby("반")["점수"].sum().sum()
    전체합계 = 결과["점수"].sum()
    assert 반별합계의합 == 전체합계


def test_미니데이터의_손계산과_일치한다():
    결과 = 정제(미니원본)
    assert len(결과) == 7
    assert 반별평균(결과)["1반"] == 80.0
    assert 반별평균(결과)["2반"] == 70.0
